"""
Agent 7 — Supervisor Schemas
============================
Defines data structures for Agent 7 (Supervisor + Verification + Report Generation):
- Structured Claims (with evidence IDs, severity, attribution flags)
- Verification Results (Existence, Support via DeBERTa-MNLI, Severity check, Divergence check)
- Investigation Synthesis
- Confidence Gate Routing
- Final Supervisor Output and LangGraph State
"""

from __future__ import annotations

from datetime import datetime, timezone
from typing import Dict, List, Any, Optional, Literal, TypedDict
from pydantic import BaseModel, Field


SEVERITY_LEVELS = {
    "informational": 0,
    "low": 1,
    "medium": 2,
    "high": 3,
    "critical": 4,
}


class StructuredClaim(BaseModel):
    """
    Individual evidence-backed claim generated by Agent 7 Call 1 (Synthesis).
    """
    claim_id: str = Field(description="Unique claim identifier, e.g. CLM-001")
    claim: str = Field(description="Narrative claim statement")
    evidence_ids: List[str] = Field(default_factory=list, description="Cited FIR finding IDs")
    severity: Literal["critical", "high", "medium", "low", "informational"] = "medium"
    is_attribution: bool = Field(default=False, description="True if claim asserts actor or malware attribution")
    confidence: float = Field(ge=0.0, le=1.0, default=0.90)
    mitre_tactics: List[str] = Field(default_factory=list)
    mitre_techniques: List[str] = Field(default_factory=list)


class ClaimVerificationResult(BaseModel):
    """
    Independent verification verdict produced by Agent 7 Call 2.
    """
    claim_id: str
    claim: str
    evidence_ids: List[str]
    verified: bool
    status: str = "unverified — requires manual confirmation"
    checks: Dict[str, bool] = Field(
        default_factory=lambda: {
            "existence": False,
            "support": False,
            "severity": False,
            "divergence": False,
        }
    )
    support_score: float = 0.0
    entailment_label: str = "unverified"
    fallback_used: bool = False
    secondary_assessment: Optional[str] = None
    flags: List[str] = Field(default_factory=list)
    evidence_details: List[Dict[str, Any]] = Field(default_factory=list)
    evidence_evaluations: List[Dict[str, Any]] = Field(default_factory=list)
    model_metadata: Dict[str, Any] = Field(default_factory=dict)


class InvestigationSynthesis(BaseModel):
    """
    Consolidated investigation synthesis from upstream agents.
    """
    case_id: str
    tenant_id: str = "default"
    executive_summary: str
    incident_narrative: str
    claims: List[StructuredClaim]
    attack_timeline: List[Dict[str, Any]] = Field(default_factory=list)
    mitre_matrix: List[Dict[str, Any]] = Field(default_factory=list)
    conflicts_resolved: List[Dict[str, Any]] = Field(default_factory=list)
    confidence_score: float = Field(ge=0.0, le=1.0, default=0.0)
    generated_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))
    synthesis_status: Optional[str] = "COMPLETED"
    synthesis_error: Optional[str] = None


class ConfidenceGateDecision(BaseModel):
    """
    Human review routing decision by Confidence Gate.
    """
    route: Literal["routine", "senior_dual"]
    requires_senior_review: bool
    reasons: List[str] = Field(default_factory=list)
    attention_items: List[str] = Field(default_factory=list)
    investigation_confidence_score: float
    verified_claim_count: int
    unverified_claim_count: int


class SupervisorOutput(BaseModel):
    """
    Complete final output payload for Agent 7.
    """
    case_id: str
    tenant_id: str = "default"
    status: str = "COMPLETED"
    synthesis: InvestigationSynthesis
    verification_results: List[ClaimVerificationResult]
    all_claims_verified: bool
    unverified_claim_count: int
    confidence_gate: ConfidenceGateDecision
    reports: Dict[str, Any] = Field(default_factory=dict)
    report_metadata: Dict[str, Any] = Field(default_factory=dict)
    timestamp: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))


class Agent7State(TypedDict, total=False):
    """
    TypedDict state object managed by LangGraph StateGraph.
    """
    case_id: str
    tenant_id: str
    context: Dict[str, Any]
    validation_passed: bool
    status: str
    error: Optional[str]
    synthesis: Dict[str, Any]
    claims: List[Dict[str, Any]]
    verification_results: List[Dict[str, Any]]
    confidence_gate: Dict[str, Any]
    review_level: str
    reports: Dict[str, Any]
    final_output: Dict[str, Any]
