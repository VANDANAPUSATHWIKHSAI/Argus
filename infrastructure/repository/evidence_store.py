def close_case(tenant_id: str, case_id: str) -> bool:
    """
    Updates the status of a CaseSession to 'closed' for the given tenant.
    Guarantees persistence across PostgreSQL and local repository fallback.
    """
    if not case_id:
        return False
        
    closed_any = False

    if _should_attempt_postgres():
        try:
            import psycopg2
            from config.settings import settings
            conn = psycopg2.connect(
                host=settings.postgres_host,
                port=settings.postgres_port,
                database=settings.postgres_db,
                user=settings.postgres_user,
                password=settings.postgres_password,
                connect_timeout=2
            )
            cur = conn.cursor()
            if tenant_id:
                cur.execute(
                    "UPDATE cases SET status = 'closed', closed_at = NOW() WHERE case_id = %s AND tenant_id = %s;",
                    (case_id, tenant_id)
                )
                if cur.rowcount > 0:
                    closed_any = True

            if not closed_any:
                cur.execute(
                    "UPDATE cases SET status = 'closed', closed_at = NOW() WHERE case_id = %s;",
                    (case_id,)
                )
                if cur.rowcount > 0:
                    closed_any = True

            conn.commit()
            conn.close()
        except Exception as e:
            logger.error("Failed to close case in Postgres: %s", e)

    # Durable local repository fallback update
    try:
        from datetime import datetime, timezone
        repo_dir = Path(REPOSITORY_DIR)
        case_dir = repo_dir / case_id
        if case_dir.exists() and case_dir.is_dir():
            session_file = case_dir / "case_session.json"
            data = {}
            if session_file.exists():
                try:
                    with open(session_file, "r", encoding="utf-8") as f:
                        data = json.load(f)
                except Exception:
                    data = {}
            data["case_id"] = case_id
            data["status"] = "closed"
            data["closed_at"] = datetime.now(timezone.utc).isoformat()
            if tenant_id and "tenant_id" not in data:
                data["tenant_id"] = tenant_id
            with open(session_file, "w", encoding="utf-8") as f:
                json.dump(data, f, indent=2)

            status_file = case_dir / "status.json"
            status_file.write_text(json.dumps({"status": "closed", "tenant_id": tenant_id}))
            closed_any = True
    except Exception as disk_e:
        logger.warning(f"Failed to update local case session file for close_case: {disk_e}")

    return closed_any

def get_evidence(tenant_id: str, evidence_id: str) -> Optional[Evidence]:
    """
    Retrieves an Evidence record by evidence_id, enforcing tenant isolation.
    """
    if not tenant_id:
        raise ValueError("tenant_id is required to fetch evidence.")
    if not evidence_id:
        raise ValueError("evidence_id is required to fetch evidence.")

    if _should_attempt_postgres():
        try:
            import psycopg2
            from config.settings import settings
            conn = psycopg2.connect(
                host=settings.postgres_host,
                port=settings.postgres_port,
                database=settings.postgres_db,
                user=settings.postgres_user,
                password=settings.postgres_password,
                connect_timeout=2
            )
            cur = conn.cursor()
            cur.execute(
                """
                SELECT e.evidence_id, e.case_id, e.filename, e.repository_path, e.uploaded_by, e.upload_timestamp, e.status, e.sha256_hash, e.encrypted, e.rfc3161_timestamp, e.metadata
                FROM evidence e
                INNER JOIN cases c ON e.case_id = c.case_id
                WHERE e.evidence_id = %s AND c.tenant_id = %s;
                """,
                (evidence_id, tenant_id)
            )
            row = cur.fetchone()
            conn.close()
            if row:
                return reconstruct_evidence_from_row(row)
            # Authoritative DB query returned 0 rows: evidence record does not exist.
            # Security Rule: A database lookup returning zero rows is never treated as permission to select a local artifact.
            return None
        except Exception as e:
            # PostgreSQL failure and ID-format mismatch fail closed; cannot silently switch to unrelated sources
            logger.error("Authoritative PostgreSQL evidence lookup failed closed: %s", e)
            return None

    # LOCAL FALLBACK: executed ONLY when PostgreSQL is offline or local storage is explicitly configured
    from infrastructure.repository.evidence_store import REPOSITORY_DIR
    from datetime import datetime
    repo_path = Path(REPOSITORY_DIR)
    if repo_path.exists():
        for case_dir in repo_path.iterdir():
            if case_dir.is_dir():
                ev_dir = case_dir / evidence_id
                if ev_dir.exists() and ev_dir.is_dir():
                    metadata_file = ev_dir / "metadata.json"
                    if metadata_file.exists():
                        try:
                            with open(metadata_file, "r", encoding="utf-8") as f:
                                data = json.load(f)
                                stored_tenant = data.get("tenant_id")
                                if stored_tenant and stored_tenant != tenant_id:
                                    return None
                                if not stored_tenant and tenant_id != "default":
                                    return None
                                data["evidence_id"] = evidence_id
                                data["case_id"] = case_dir.name
                                raw_status = str(data.get("status", "")).lower()
                                valid_statuses = {s.value for s in EvidenceStatus}
                                if raw_status in valid_statuses:
                                    data["status"] = EvidenceStatus(raw_status)
                                else:
                                    data["status"] = EvidenceStatus.STORED
                                return Evidence(**data)
                        except Exception as e:
                            logger.error("Failed to read metadata.json: %s", e)
                    orig_dir = ev_dir / "original"
                    if orig_dir.exists() and tenant_id == "default":
                        files = list(orig_dir.iterdir())
                        if files:
                            file_path = files[0]
                            return Evidence(
                                evidence_id=evidence_id,
                                case_id=case_dir.name,
                                filename=file_path.name,
                                file_path=str(file_path),
                                uploaded_by="Unknown (Local Fallback)",
                                upload_timestamp=datetime.fromtimestamp(file_path.stat().st_ctime),
                                status=EvidenceStatus.STORED,
                                original_repository_path=str(file_path),
                                repository_path=str(file_path),
                                metadata={"size_bytes": file_path.stat().st_size, "tenant_id": "default"}
                            )
    return None


