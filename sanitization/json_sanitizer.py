"""
Robust JSON Sanitizer & Parser for Forensic Agent Outputs
=========================================================
Safely cleans, repairs, and parses structured LLM outputs without inventing
or altering forensic facts, evidence IDs, or confidence scores.

Handles:
- Markdown fences (```json ... ```, ``` ... ```)
- Outermost boundary extraction
- Trailing commas before closing braces/brackets
- Unterminated strings caused by token limit truncation
- Unclosed container brackets/braces
- Unescaped control characters (newlines/tabs in strings)
"""

from __future__ import annotations

import json
import logging
import re
from typing import Any, Tuple, Optional

logger = logging.getLogger(__name__)


def robust_json_loads(raw_text: str) -> Tuple[Optional[Any], Optional[str]]:
    """
    Robustly parses JSON text generated by LLMs without hallucinating content.
    Returns (parsed_object, None) on success, or (None, error_message) on failure.
    """
    if not raw_text or not isinstance(raw_text, str) or not raw_text.strip():
        return None, "Empty LLM output"

    cleaned = raw_text.strip()

    # 1. Strip markdown fences
    if "```json" in cleaned:
        cleaned = cleaned.split("```json", 1)[1].split("```", 1)[0].strip()
    elif "```" in cleaned:
        cleaned = cleaned.split("```", 1)[1].split("```", 1)[0].strip()

    # 2. Extract outermost JSON structure
    start_brace = cleaned.find("{")
    start_bracket = cleaned.find("[")

    if start_brace != -1 and (start_bracket == -1 or start_brace < start_bracket):
        end_brace = cleaned.rfind("}")
        if end_brace != -1:
            candidate = cleaned[start_brace:end_brace + 1]
        else:
            candidate = cleaned[start_brace:]
    elif start_bracket != -1:
        end_bracket = cleaned.rfind("]")
        if end_bracket != -1:
            candidate = cleaned[start_bracket:end_bracket + 1]
        else:
            candidate = cleaned[start_bracket:]
    else:
        candidate = cleaned

    # 3. Attempt direct parse with strict=False (allows raw newlines/tabs inside strings)
    try:
        return json.loads(candidate, strict=False), None
    except Exception as initial_err:
        last_error = str(initial_err)

    # 4. Repair trailing commas before closing braces/brackets
    repaired = re.sub(r',\s*([\]}])', r'\1', candidate)
    try:
        return json.loads(repaired, strict=False), None
    except Exception as trailing_err:
        last_error = str(trailing_err)

    # 5. Repair unterminated string & unclosed containers caused by token limits
    in_string = False
    escape = False
    chars = []
    open_containers = []

    for ch in repaired:
        if escape:
            escape = False
            chars.append(ch)
            continue
        if ch == '\\':
            escape = True
            chars.append(ch)
            continue
        if ch == '"':
            in_string = not in_string
            chars.append(ch)
            continue
        if not in_string:
            if ch in ('{', '['):
                open_containers.append('}' if ch == '{' else ']')
            elif ch in ('}', ']'):
                if open_containers and open_containers[-1] == ch:
                    open_containers.pop()
        chars.append(ch)

    fixed_str = "".join(chars)
    if in_string:
        fixed_str += '"'

    while open_containers:
        fixed_str += open_containers.pop()

    # Clean trailing commas in closed string
    fixed_str = re.sub(r',\s*([\]}])', r'\1', fixed_str)

    try:
        return json.loads(fixed_str, strict=False), None
    except Exception as repair_err:
        logger.debug("Robust JSON repair could not parse string: %s", repair_err)
        return None, last_error

