"""
Unit and Integration Test Suite for Agent 6 — Impact Assessment
================================================================
Comprehensive verification of evidence-grounded asset evaluation,
tenant isolation, structured validation status, and integration with Agent 5B:

1. Critical impact with valid asset-level evidence.
2. Missing evidence IDs.
3. Unauthorized or cross-tenant evidence references.
4. An asset name absent from current-case records.
5. Historical similarity without current evidence of compromise.
6. Partial evidence supporting only some affected assets.
7. Recommendations issued with uncertainty clearly identified.
"""

import unittest
from unittest.mock import MagicMock

from agents.agent6_impact_assessment import (
    ImpactAssessmentAgent,
    AssetImpactDetail,
    ImmediateRecommendation,
    ImpactAssessmentOutput
)


class DummyModel:
    def __init__(self, name="Qwen3-14B"):
        self.model_name = name

    def generate(self, prompt: str, system_prompt: str = "") -> str:
        return "Impact narrative generated by model."


class TestAgent6ImpactAssessment(unittest.TestCase):

    def setUp(self):
        self.model = DummyModel()
        self.mock_gateway = MagicMock()
        self.mock_gateway.sanitize = lambda text, field_name="unstructured": text
        self.agent = ImpactAssessmentAgent(
            model=self.model,
            fir_repo=None,
            sanitization_gateway=self.mock_gateway,
            tenant_id="tenant_alpha"
        )

    # 1. Critical impact with valid asset-level evidence
    def test_01_critical_impact_with_valid_asset_level_evidence(self):
        context = {
            "tenant_id": "tenant_alpha",
            "affected_assets": ["WORKSTATION-41"],
            "fir_findings": [
                {
                    "finding_id": "FIR-001",
                    "tenant_id": "tenant_alpha",
                    "fact": "cmd.exe spawned powershell.exe and connected to C2 on host WORKSTATION-41",
                    "severity": "critical"
                }
            ]
        }

        result = self.agent.run("CASE-001", context)

        self.assertEqual(result["validation_status"], "supported")
        self.assertIn("FIR-001", result["evidence_ids"])
        self.assertEqual(len(result["asset_impacts"]), 1)
        impact = result["asset_impacts"][0]
        self.assertEqual(impact["asset_name"], "WORKSTATION-41")
        self.assertEqual(impact["status"], "confirmed_compromise")
        self.assertIn("FIR-001", impact["supporting_evidence_ids"])
        self.assertIn("FIR-001", result["claim"])

    # 2. Missing evidence IDs
    def test_02_missing_evidence_ids(self):
        context = {
            "tenant_id": "tenant_alpha",
            "affected_assets": ["WORKSTATION-41"],
            "fir_findings": []  # No evidence provided
        }

        result = self.agent.run("CASE-002", context)

        self.assertEqual(result["validation_status"], "insufficient_evidence")
        self.assertEqual(result["evidence_ids"], [])
        self.assertEqual(len(result["asset_impacts"]), 1)
        self.assertEqual(result["asset_impacts"][0]["status"], "unsupported_in_evidence")
        self.assertIn("Insufficient", result["claim"])

    # 3. Unauthorized or cross-tenant evidence references
    def test_03_unauthorized_or_cross_tenant_evidence_rejected(self):
        context = {
            "tenant_id": "tenant_alpha",
            "affected_assets": ["WORKSTATION-41"],
            "fir_findings": [
                {
                    "finding_id": "FIR-FOREIGN-999",
                    "tenant_id": "tenant_intruder",  # Cross-tenant finding
                    "fact": "Compromise verified on WORKSTATION-41"
                }
            ]
        }

        result = self.agent.run("CASE-003", context)

        # Cross-tenant evidence must be completely rejected
        self.assertNotIn("FIR-FOREIGN-999", result["evidence_ids"])
        self.assertEqual(result["validation_status"], "insufficient_evidence")
        self.assertEqual(result["asset_impacts"][0]["status"], "unsupported_in_evidence")

    # 4. An asset name absent from current-case records
    def test_04_asset_name_absent_from_current_case_records(self):
        context = {
            "tenant_id": "tenant_alpha",
            "affected_assets": ["SRV-FINANCE-01"],  # Never mentioned in FIR findings
            "fir_findings": [
                {
                    "finding_id": "FIR-004",
                    "tenant_id": "tenant_alpha",
                    "fact": "Malware activity observed on WORKSTATION-99"
                }
            ]
        }

        result = self.agent.run("CASE-004", context)

        self.assertEqual(result["validation_status"], "insufficient_evidence")
        self.assertEqual(result["evidence_ids"], [])
        self.assertEqual(result["asset_impacts"][0]["status"], "unsupported_in_evidence")
        self.assertIn("SRV-FINANCE-01", result["asset_impacts"][0]["rationale"])
        self.assertNotIn("FIR-004", result["asset_impacts"][0]["supporting_evidence_ids"])

    # 5. Historical similarity without current evidence of compromise
    def test_05_historical_similarity_cannot_prove_compromise(self):
        context = {
            "tenant_id": "tenant_alpha",
            "affected_assets": ["SRV-FINANCE-01"],
            "fir_findings": [],
            "agent5b_handoff": {
                "case_id": "CASE-005",
                "similarity_metrics": {"composite_similarity": 0.95},
                "behavior_comparisons": {"common_behaviors": ["PowerShell Execution"]},
                "supporting_evidence_references": ["FIR-GENERIC"]
            }
        }

        result = self.agent.run("CASE-005", context)

        # Even with 0.95 composite similarity from Agent 5B, SRV-FINANCE-01 cannot be marked compromised
        self.assertEqual(result["validation_status"], "insufficient_evidence")
        self.assertEqual(result["asset_impacts"][0]["status"], "unsupported_in_evidence")
        self.assertEqual(result["evidence_ids"], [])
        self.assertIn("does not establish confirmed compromise", result["claim"].lower())

    # 6. Partial evidence supporting only some affected assets
    def test_06_partial_evidence_supporting_some_affected_assets(self):
        context = {
            "tenant_id": "tenant_alpha",
            "affected_assets": ["WORKSTATION-41", "SRV-FINANCE-01"],
            "fir_findings": [
                {
                    "finding_id": "FIR-006",
                    "tenant_id": "tenant_alpha",
                    "fact": "Host WORKSTATION-41 dumped LSASS process memory"
                }
            ]
        }

        result = self.agent.run("CASE-006", context)

        self.assertEqual(result["validation_status"], "partially_supported")
        self.assertEqual(result["evidence_ids"], ["FIR-006"])
        
        impact_by_name = {a["asset_name"]: a for a in result["asset_impacts"]}
        self.assertEqual(impact_by_name["WORKSTATION-41"]["status"], "confirmed_compromise")
        self.assertEqual(impact_by_name["WORKSTATION-41"]["supporting_evidence_ids"], ["FIR-006"])
        self.assertEqual(impact_by_name["SRV-FINANCE-01"]["status"], "unsupported_in_evidence")
        self.assertEqual(impact_by_name["SRV-FINANCE-01"]["supporting_evidence_ids"], [])

        # Claim must explicitly distinguish confirmed from unconfirmed
        self.assertIn("WORKSTATION-41", result["claim"])
        self.assertIn("SRV-FINANCE-01", result["claim"])
        self.assertIn("unconfirmed pending", result["claim"])

    # 7. Recommendations issued with uncertainty clearly identified
    def test_07_recommendations_with_uncertainty_distinguished(self):
        context = {
            "tenant_id": "tenant_alpha",
            "affected_assets": ["WORKSTATION-41", "SRV-FINANCE-01"],
            "fir_findings": [
                {
                    "finding_id": "FIR-007",
                    "tenant_id": "tenant_alpha",
                    "fact": "PowerShell dropper executed on WORKSTATION-41"
                }
            ]
        }

        result = self.agent.run("CASE-007", context)

        recs = result["immediate_recommendations"]
        self.assertGreaterEqual(len(recs), 2)

        # Containment is provisional for confirmed asset
        containment = [r for r in recs if "Containment" in r["action"]]
        self.assertEqual(len(containment), 1)
        self.assertEqual(containment[0]["urgency"], "critical")
        self.assertEqual(containment[0]["status"], "provisional_recommended")
        self.assertIn("WORKSTATION-41", containment[0]["action"])

        # Triage for unconfirmed asset is contingent on investigation
        triage = [r for r in recs if "Telemetry" in r["action"] or "Triage" in r["action"]]
        self.assertEqual(len(triage), 1)
        self.assertEqual(triage[0]["status"], "contingent_on_investigation")
        self.assertIn("SRV-FINANCE-01", triage[0]["action"])
        self.assertIn("lack confirmed forensic evidence", triage[0]["rationale"])


if __name__ == "__main__":
    unittest.main()
